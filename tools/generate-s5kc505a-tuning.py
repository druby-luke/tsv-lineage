"""Generate SoftISP tuning from explicitly supplied Lenovo reference JSON.

The input format is Mei Tao's decoded chromatix 0x0309 data, distributed by
rickx/ubuntu-thinksmart. Only the shared CCM, black-level and LSC fields are
used. No residual file is searched for or applied. Sensor-space meshes stay
unflipped; the display mounting rotation is not a sensor calibration transform.
The 0.12 AGC luminance baseline is empirical policy, not vendor calibration.
"""

import argparse
import json
import math
from pathlib import Path

CCM_TEMPERATURES = {"H": 2300, "A": 2850, "TL84": 4000, "D50": 5000, "D65": 6500}
LSC_TEMPERATURES = {"H": 2300, "A": 2850, "TL84": 4000, "D65": 6500}
GRID_SIZE = 17
# The largest exact-unity byte that retains the vendor's 4.30724 maximum.
GAIN_UNIT = 59
GAIN_SCALE = 255 / GAIN_UNIT


def numeric_values(values, count, name):
    """Validate the shape and finite numeric values of one decoded array."""
    if len(values) != count or not all(
        isinstance(value, (int, float)) and not isinstance(value, bool)
        and math.isfinite(value) for value in values
    ):
        raise ValueError(f"{name}: expected {count} finite numbers")
    return values


def resample_rows(values):
    """Interpolate the vendor's 13 uniform rows onto 17 uniform rows."""
    result = []
    for row in range(GRID_SIZE):
        source_y = row * 12 / (GRID_SIZE - 1)
        top = int(source_y)
        bottom = min(top + 1, 12)
        fraction = source_y - top
        for column in range(GRID_SIZE):
            gain = (values[top * GRID_SIZE + column] * (1 - fraction)
                    + values[bottom * GRID_SIZE + column] * fraction)
            if not 0 < gain <= GAIN_SCALE:
                raise ValueError(f"LSC gain {gain} is outside the representable range")
            # Keep register-domain fractions until mode-crop resampling.
            result.append(gain * GAIN_UNIT)
    return result


def generate(data):
    """Combine shared calibration with the explicit empirical AGC baseline."""
    if data["mesh"] != [13, 17] or data["bayer"] != "GRBG":
        raise ValueError("Expected the Lenovo 13x17 GRBG calibration")
    if data["black_level_10bit"] != 64:
        raise ValueError("Unexpected Lenovo black pedestal")

    lines = [
        "# Vendor numeric references; transforms, limits and provenance:",
        "# patches/external/libcamera/0101-describe-vendor-s5kc505a-sensor.patch",
        "# Generated by tools/generate-s5kc505a-tuning.py; no unit residual.",
        "%YAML 1.1", "---", "version: 1", "algorithms:",
        "  - BlackLevel:", "      blackLevel: 4096", "  - Awb:",
        "  - Ccm:", "      ccms:",
    ]
    for name, temperature in sorted(CCM_TEMPERATURES.items(), key=lambda item: item[1]):
        values = numeric_values(data["ccm"][name], 9, f"CCM/{name}")
        lines.append(f"        - ct: {temperature}")
        lines.append("          ccm: [" + ", ".join(map(str, values[:3])) + ",")
        lines.append("                " + ", ".join(map(str, values[3:6])) + ",")
        lines.append("                " + ", ".join(map(str, values[6:])) + "]")

    lines.extend(["  - Lsc:", "      type: table",
                  f"      gainScale: {GAIN_SCALE}", "      sets:"])
    for name, temperature in sorted(LSC_TEMPERATURES.items(), key=lambda item: item[1]):
        source = data["lsc"][name]
        channels = {
            key: numeric_values(source[key], 13 * 17, f"LSC/{name}/{key}")
            for key in ("r_gain", "gr_gain", "gb_gain", "b_gain")
        }
        if any(value <= 0 for values in channels.values() for value in values):
            raise ValueError(f"LSC/{name}: nonpositive gain")
        green = [(gr + gb) / 2 for gr, gb in
                 zip(channels["gr_gain"], channels["gb_gain"])]
        lines.append(f"        - ct: {temperature}")
        for key, values in (("r", channels["r_gain"]), ("g", green),
                            ("b", channels["b_gain"])):
            samples = resample_rows(values)
            for row in range(GRID_SIZE):
                prefix = f"          {key}: [" if row == 0 else "              "
                suffix = "]" if row == GRID_SIZE - 1 else ","
                entries = samples[row * GRID_SIZE:(row + 1) * GRID_SIZE]
                lines.append(prefix + ", ".join(f"{value:.6f}" for value in entries) + suffix)
    lines.extend(["  - Adjust:", "  - Agc:",
                  "      relativeLuminanceTarget: 0.12", "..."])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path, help="Decoded Lenovo reference JSON")
    parser.add_argument("output", type=Path, help="Destination SoftISP YAML")
    args = parser.parse_args()
    args.output.write_text(generate(json.loads(args.reference.read_text())))


if __name__ == "__main__":
    main()
